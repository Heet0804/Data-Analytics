-- A. KPI'S
-- Q1. TOTAL REVENUE:
SELECT SUM(TOTAL_FARE) AS TOTAL_REVENUE
FROM RIDE_TRIPS
WHERE TRIP_STATUS="COMPLETED";

-- Q2. TOTAL TRIPS REQUESTED
SELECT COUNT(TRIP_ID) AS TOTAL_TRIPS_REQUESTED
FROM RIDE_TRIPS;

-- Q3. COMPLETED TRIPS
SELECT COUNT(TRIP_ID) AS COMPLETED_TRIPS
FROM RIDE_TRIPS
WHERE TRIP_STATUS="COMPLETED";

-- Q4. AVG. FARE PER TRIP
SELECT SUM(TOTAL_FARE)/COUNT(TRIP_ID) AS AVG_FARE_PER_TRIP
FROM RIDE_TRIPS
WHERE TRIP_STATUS="COMPLETED";

-- Q5. AVG. TRIP DISTANCE
SELECT AVG(DISTANCE_KM) AS AVG_TRIP_DISTANCE
FROM RIDE_TRIPS
WHERE TRIP_STATUS="COMPLETED";

-- Q6. CANCELLATION RATE
SELECT SUM((CASE WHEN TRIP_STATUS="CANCELLED" THEN 1 ELSE 0 END*100))/(COUNT(TRIP_ID)) AS CANCELLATION_RATE
FROM RIDE_TRIPS;

-- Q7. AVG. DRIVER RATING
SELECT AVG(DRIVER_RATING) AS AVG_DRIVER_RATING
FROM RIDE_TRIPS
WHERE TRIP_STATUS="COMPLETED";

-- B. DAILY TREND FOR TOTAL TRIPS
SELECT DAYNAME(TRIP_DATE) AS WEEKDAY , COUNT(TRIP_ID) AS TOTAL_TRIPS
FROM RIDE_TRIPS
GROUP BY WEEKDAY
ORDER BY TOTAL_TRIPS DESC;

-- C. HOURLY TRENDS FOR TRIPS & SURGE
SELECT HOUR(PICKUP_TIME) AS HOURS , COUNT(TRIP_ID) AS TOTAL_TRIPS , AVG(SURGE_MULTIPLIER) AS SURGE_MULTIPLIER
FROM RIDE_TRIPS
GROUP BY HOURS
ORDER BY HOURS ASC;

-- D. % OF REVENUE BY VECHILE TYPE
SELECT VEHICLE_TYPE , COUNT(TRIP_ID) AS TOTAL_TRIPS , SUM(TOTAL_FARE) AS TOTAL_FARE , SUM(TOTAL_FARE)*100/(SELECT SUM(TOTAL_FARE) FROM RIDE_TRIPS WHERE TRIP_STATUS="COMPLETED") AS PERCENTAGE
FROM RIDE_TRIPS
GROUP BY VEHICLE_TYPE
ORDER BY TOTAL_FARE DESC;

-- E. Top 10 Pickup Areas by Revenue
SELECT PICKUP_AREA , COUNT(TRIP_ID) AS COMPLETED_TRIPS , SUM(TOTAL_FARE) AS TOTAL_REVENUE
FROM RIDE_TRIPS
WHERE TRIP_STATUS="COMPLETED"
GROUP BY PICKUP_AREA
ORDER BY TOTAL_REVENUE DESC
LIMIT 10; 

-- F. Monthly Revenue Trend
SELECT MONTHNAME(TRIP_DATE) AS MONTHS ,COUNT(TRIP_ID) AS COMPLETED_TRIPS ,  SUM(TOTAL_FARE) AS TOTAL_REVENUE
FROM RIDE_TRIPS
WHERE TRIP_STATUS="COMPLETED"
GROUP BY MONTHS , MONTH(TRIP_DATE)
ORDER BY MONTH(TRIP_DATE) ASC;

-- G. Cancellation Rate by Weather
SELECT WEATHER  , COUNT(TRIP_ID) AS TOTAL_REQUESTS , SUM(CASE WHEN TRIP_STATUS="CANCELLED" THEN 1 ELSE 0 END) AS CANCELLED_TRIPS ,  SUM((CASE WHEN TRIP_STATUS="CANCELLED" THEN 1 ELSE 0 END*100))/(COUNT(TRIP_ID)) AS CANCELLATION_RATE
FROM RIDE_TRIPS
GROUP BY WEATHER
ORDER BY CANCELLATION_RATE DESC;

-- H. WHY ARE TRIPS CANCELLED
SELECT CANCELLATION_REASON , COUNT(TRIP_ID) AS TRIPS_CANCELLED , COUNT(TRIP_ID)*100/(SELECT COUNT(TRIP_ID) FROM RIDE_TRIPS WHERE TRIP_STATUS="CANCELLED") AS PC
FROM RIDE_TRIPS
WHERE TRIP_STATUS="CANCELLED"
GROUP BY CANCELLATION_REASON
ORDER BY TRIPS_CANCELLED DESC;

-- I. % of Trips by Payment Mode
SELECT PAYMENT_MODE , COUNT(TRIP_ID) AS TOTAL_TRIPS , COUNT(TRIP_ID)*100/(SELECT COUNT(TRIP_ID) FROM RIDE_TRIPS WHERE TRIP_STATUS="COMPLETED") AS PC
FROM RIDE_TRIPS
WHERE TRIP_STATUS="COMPLETED"
GROUP BY PAYMENT_MODE
ORDER BY TOTAL_TRIPS DESC;

-- J. Surge Pricing Impact
SELECT SURGE_BAND , COUNT(TRIP_ID) AS TOTAL_TRIPS , SUM(CASE WHEN TRIP_STATUS="CANCELLED" THEN 1 ELSE 0 END) * 100 /COUNT(TRIP_ID) AS CANCELLATION_RATE , 
AVG(CASE WHEN TRIP_STATUS="COMPLETED" THEN TOTAL_FARE END) AS AVG_FARE
FROM (SELECT * ,
CASE 
	WHEN SURGE_MULTIPLIER = 1 THEN "1.NO SURGE"
    WHEN SURGE_MULTIPLIER <= 1.5 THEN "2.LOW SURGE(1.2X - 1.5X)"
    ELSE "3.HIGH SURGE(1.8X - 2.5X)"
END AS SURGE_BAND
FROM RIDE_TRIPS
) T    
GROUP BY SURGE_BAND
ORDER BY SURGE_BAND;

-- K. Top 5 Busiest Routes
SELECT CONCAT(PICKUP_AREA , " to " , DROP_AREA) AS ROUTE , COUNT(TRIP_ID) AS TOTAL_TRIPS , SUM(TOTAL_FARE) AS TOTAL_REVENUE
FROM RIDE_TRIPS
WHERE TRIP_STATUS="COMPLETED"
GROUP BY ROUTE
ORDER BY TOTAL_TRIPS DESC
LIMIT 5;

-- L. BOTTOM 5 ROUTES
SELECT CONCAT(PICKUP_AREA , " to " , DROP_AREA) AS ROUTE , COUNT(TRIP_ID) AS TOTAL_TRIPS , SUM(TOTAL_FARE) AS TOTAL_REVENUE
FROM RIDE_TRIPS
WHERE TRIP_STATUS="COMPLETED"
GROUP BY ROUTE
ORDER BY TOTAL_TRIPS ASC
LIMIT 5;

-- M. TOP 5 DRIVERS BY EARNINGS
SELECT DRIVER_ID , VEHICLE_TYPE , COUNT(TRIP_ID) AS TOTAL_TRIPS , SUM(TOTAL_FARE) AS TOTAL_EARNINGS , AVG(DRIVER_RATING) AS AVG_RATING
FROM RIDE_TRIPS
WHERE TRIP_STATUS="COMPLETED"
GROUP BY DRIVER_ID , VEHICLE_TYPE
ORDER BY TOTAL_EARNINGS DESC
LIMIT 5;