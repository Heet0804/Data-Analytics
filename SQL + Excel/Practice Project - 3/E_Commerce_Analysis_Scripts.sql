USE E_COMMERCE;

-- A. KPI'S
-- Q1. TOTAL_REVENUE
SELECT SUM(ORDER_VALUE) AS TOTAL_REVENUE
FROM ECOMMERCE_ORDERS
WHERE ORDER_STATUS="DELIVERED";

-- Q2. TOTAL_ORDERS_PLACED
SELECT COUNT(ORDER_ID) AS TOTAL_ORDERS_PLACED
FROM ECOMMERCE_ORDERS;

-- Q3. DELIVERED_ORDERS
SELECT COUNT(ORDER_ID) AS DELIVERED_ORDERS
FROM ECOMMERCE_ORDERS
WHERE ORDER_STATUS="DELIVERED";

-- Q4. AVG_ORDER_VALUE
SELECT ROUND(SUM(ORDER_VALUE)/COUNT(ORDER_ID),2) AS AVG_ORDER_VALUE
FROM ECOMMERCE_ORDERS
WHERE ORDER_STATUS="DELIVERED";

-- Q5. CANCELLATION_RATE
SELECT ROUND(SUM(CASE WHEN ORDER_STATUS="CANCELLED" THEN 1 ELSE 0 END)*100/COUNT(ORDER_ID),2) AS CANCELLATION_RATE
FROM ECOMMERCE_ORDERS;

-- Q6. RETURN_RATE
SELECT ROUND(SUM(CASE WHEN ORDER_STATUS="RETURNED" THEN 1 ELSE 0 END)*100/COUNT(ORDER_ID),2) AS RETURN_RATE
FROM ECOMMERCE_ORDERS
WHERE ORDER_STATUS IN ("DELIVERED" , "RETURNED");

-- Q7. AVG_CUSTOMER_RATING
SELECT ROUND(AVG(CUSTOMER_RATING),2) AS AVG_CUSTOMER_RATING
FROM ECOMMERCE_ORDERS
WHERE ORDER_STATUS="DELIVERED";

-- Q8. AVG_DELIVERY_DAYS
SELECT ROUND(AVG(DELIVERY_DAYS),2) AS AVG_DELIVERY_DAYS
FROM ECOMMERCE_ORDERS
WHERE ORDER_STATUS IN ("DELIVERED" , "RETURNED");

-- B. Daily Trend for Total Orders
SELECT DAYNAME(ORDER_DATE) AS DAYS , COUNT(ORDER_ID) AS TOTAL_ORDERS
FROM ECOMMERCE_ORDERS
GROUP BY DAYS
ORDER BY TOTAL_ORDERS DESC;

-- C. Hourly Trend for Orders & Discounts
SELECT HOUR(ORDER_TIME) AS HOUR, COUNT(ORDER_ID) AS TOTAL_ORDERS , ROUND(AVG(DISCOUNT_PCT),2) AS AVG_DISCOUNT
FROM ECOMMERCE_ORDERS
GROUP BY HOUR
ORDER BY HOUR ASC;

-- D. % OF REVENUE BY CATEGORY
SELECT CATEGORY , SUM(ORDER_VALUE) AS TOTAL_REVENUE , ROUND(SUM(ORDER_VALUE)*100/(SELECT SUM(ORDER_VALUE) FROM ECOMMERCE_ORDERS WHERE ORDER_STATUS="DELIVERED"),2) AS REVENUE_PERCEMT
FROM ECOMMERCE_ORDERS
WHERE ORDER_STATUS="DELIVERED"
GROUP BY CATEGORY
ORDER BY TOTAL_REVENUE DESC;

-- E. TOP 10 CITIES BY REVENUE
SELECT CITY , COUNT(ORDER_ID) AS DELIVERED_ORDERS , SUM(ORDER_VALUE) AS TOTAL_REVENUE
FROM ECOMMERCE_ORDERS
WHERE ORDER_STATUS="DELIVERED"
GROUP BY CITY
ORDER BY TOTAL_REVENUE DESC
LIMIT 10;

-- F. MONTHLY REVENUE TREND
SELECT MONTHNAME(ORDER_DATE) AS MONTH , COUNT(ORDER_ID) AS DELIVERED_ORDERS , SUM(ORDER_VALUE) AS TOTAL_REVENUE
FROM ECOMMERCE_ORDERS
WHERE ORDER_STATUS="DELIVERED"
GROUP BY MONTH , MONTH(ORDER_DATE)
ORDER BY MONTH(ORDER_DATE);

-- G. RETURN RATE BY CATEGORY
SELECT CATEGORY , COUNT(ORDER_ID) AS SHIPPED_ORDERS , SUM(CASE WHEN ORDER_STATUS="RETURNED" THEN 1 ELSE 0 END) AS RETURNED_ORDERS , ROUND(SUM(CASE WHEN ORDER_STATUS="RETURNED" THEN 1 ELSE 0 END)*100/COUNT(ORDER_ID),2) AS RETURN_RATE
FROM ECOMMERCE_ORDERS
WHERE ORDER_STATUS IN ("DELIVERED" , "RETURNED")
GROUP BY CATEGORY
ORDER BY RETURN_RATE DESC;

-- H. WHY ARE ORDERS CANCELLED?
SELECT CANCEL_RETURN_REASON , COUNT(ORDER_ID) AS CANCELLED_ORDERS , ROUND(COUNT(ORDER_ID)*100/(SELECT COUNT(ORDER_ID) FROM ECOMMERCE_ORDERS WHERE ORDER_STATUS="CANCELLED"),2) AS PCT_OF_CANCEL
FROM ECOMMERCE_ORDERS
WHERE ORDER_STATUS="CANCELLED"
GROUP BY CANCEL_RETURN_REASON
ORDER BY CANCELLED_ORDERS DESC;

-- I. % OF ORDERS BY PAYMENT MODE
SELECT PAYMENT_MODE , COUNT(ORDER_ID) AS TOTAL_ORDER , ROUND(COUNT(ORDER_ID)*100/(SELECT COUNT(ORDER_ID) FROM ECOMMERCE_ORDERS),2) AS PCT_PAYMENT
FROM ECOMMERCE_ORDERS
GROUP BY PAYMENT_MODE
ORDER BY TOTAL_ORDER DESC;

-- J. DISCOUNT IMPACT
SELECT DISCOUNT_BANDS , COUNT(ORDER_ID) AS TOTAL_ORDERS ,
ROUND(SUM(CASE WHEN ORDER_STATUS="CANCELLED" THEN 1 ELSE 0 END)*100/COUNT(ORDER_ID),2) AS CANCEL_PCT , 
ROUND(SUM(CASE WHEN ORDER_STATUS="RETURNED" THEN 1 ELSE 0 END)*100/SUM(CASE WHEN ORDER_STATUS IN ("DELIVERED" , "RETURNED") THEN 1 ELSE 0 END),2) AS RETURN_PCT ,
ROUND(AVG(CASE WHEN ORDER_STATUS="DELIVERED" THEN ORDER_VALUE END),2) AS AVG_ORDER_VALUE 
FROM ( 
SELECT * , 
CASE 
	WHEN DISCOUNT_PCT = 0 THEN "1. NO DISCOUNT"
    WHEN DISCOUNT_PCT <= 20 THEN "2. LOW DISCOUNT (5% - 20%)"
    WHEN DISCOUNT_PCT <= 40 THEN "3. MEDIUM DISCOUNT (25% - 40%)"
    ELSE "4. HIGH DISCOUNT (50% - 60%)"
END AS DISCOUNT_BANDS
FROM ECOMMERCE_ORDERS
)T
GROUP BY DISCOUNT_BANDS
ORDER BY DISCOUNT_BANDS;

-- K. TOP 5 BRANDS BY REVENUE
SELECT BRAND , CATEGORY , COUNT(ORDER_ID) AS TOTAL_ORDERS , SUM(ORDER_VALUE) AS TOTAL_REVENUE
FROM ECOMMERCE_ORDERS
WHERE ORDER_STATUS="DELIVERED"
GROUP BY BRAND , CATEGORY
ORDER BY TOTAL_REVENUE DESC
LIMIT 5;

-- L. BOTTOM 5 BRANDS
SELECT BRAND , CATEGORY , COUNT(ORDER_ID) AS TOTAL_ORDERS , SUM(ORDER_VALUE) AS TOTAL_REVENUE
FROM ECOMMERCE_ORDERS
WHERE ORDER_STATUS="DELIVERED"
GROUP BY BRAND , CATEGORY
ORDER BY TOTAL_REVENUE ASC
LIMIT 5;

-- M. TOP 5 SELLERS BY REVENUE
SELECT SELLER_ID , COUNT(ORDER_ID) AS TOTAL_ORDERS , SUM(ORDER_VALUE) AS TOTAL_REVENUE , ROUND(AVG(CUSTOMER_RATING),2) AS CUSTOMER_RATING
FROM ECOMMERCE_ORDERS
WHERE ORDER_STATUS="DELIVERED"
GROUP BY SELLER_ID
ORDER BY TOTAL_REVENUE DESC
LIMIT 5;