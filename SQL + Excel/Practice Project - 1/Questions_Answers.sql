-- Q1. List all currently active teams with their city, sorted by team name.
SELECT TEAM_NAME , CITY 
FROM TEAMS
WHERE IS_ACTIVE=1
ORDER BY TEAM_NAME;

-- Q2. How many franchises have played in the IPL in total, how many are active and how many are defunct?
SELECT COUNT(*) AS TOTAL_TEAMS , SUM(IS_ACTIVE) AS ACTIVE_TEAMS , COUNT(*)-SUM(IS_ACTIVE) AS DEFUNCT_TEAMS
FROM TEAMS;

-- Q3. How many seasons are recorded and how many matches were played across all of them?
SELECT COUNT(*) AS TOTAL_SEASONS , SUM(TOTAL_MATCHES) AS TOTAL_MATCHES
FROM SEASONS;

-- Q4. Which venues have a capacity above 50,000? Show the biggest first.
SELECT *
FROM VENUES
WHERE CAPACITY>50000
ORDER BY CAPACITY DESC;

-- Q5. How many players are there in each role?
SELECT ROLE , COUNT(*) AS TOTAL_PLAYERS
FROM PLAYERS
GROUP BY ROLE
ORDER BY TOTAL_PLAYERS DESC;

-- Q6. Among players who are in a 2025 squad, how many are Indian and how many are overseas?
SELECT CASE WHEN NATIONALITY="INDIA" THEN "INDIAN" ELSE "OVERSEAS" END AS NATIONALITY , COUNT(*) AS TOTAL_PLAYERS
FROM PLAYERS
WHERE CURRENT_TEAM_ID IS NOT NULL
GROUP BY CASE WHEN NATIONALITY="INDIA" THEN "INDIAN" ELSE "OVERSEAS" END;

-- Q7. What is the squad size of each active team in this dataset?
SELECT TEAMS.TEAM_NAME , COUNT(*) AS SQUAD_SIZE 
FROM TEAMS
JOIN PLAYERS
ON TEAMS.TEAM_ID=PLAYERS.CURRENT_TEAM_ID
GROUP BY TEAMS.TEAM_NAME
ORDER BY SQUAD_SIZE DESC;

-- Q8. How many IPL titles has each team won? Show only teams with at least one title.
SELECT TEAMS.TEAM_NAME , COUNT(*) AS TITLE_WINNERS
FROM TEAMS
JOIN SEASONS
ON TEAMS.TEAM_ID=SEASONS.CHAMPION_TEAM_ID
GROUP BY TEAMS.TEAM_NAME
ORDER BY TITLE_WINNERS DESC;

-- Q9. Show every season with its champion and runner-up team names.
SELECT SEASONS.SEASON_YEAR AS SEASON ,  TEAMS1.TEAM_NAME AS CHAMPION , TEAMS2.TEAM_NAME AS RUNNER_UP
FROM SEASONS
JOIN TEAMS TEAMS1 ON SEASONS.CHAMPION_TEAM_ID=TEAMS1.TEAM_ID
JOIN TEAMS TEAMS2 ON SEASONS.RUNNER_UP_TEAM_ID=TEAMS2.TEAM_ID;

-- Q10. In which city and venue was each final played? Show the year, venue, city and country.
SELECT SEASONS.SEASON_YEAR , VENUES.VENUE_NAME , VENUES.CITY , VENUES.COUNTRY
FROM SEASONS
JOIN VENUES 
ON SEASONS.FINAL_VENUE_ID=VENUES.VENUE_ID;

-- Q11. Which teams have reached an IPL final but never won the title?
SELECT DISTINCT TEAMS.TEAM_NAME 
FROM SEASONS
JOIN TEAMS ON SEASONS.RUNNER_UP_TEAM_ID=TEAMS.TEAM_ID	
WHERE TEAMS.TEAM_ID NOT IN (SELECT CHAMPION_TEAM_ID FROM SEASONS);

-- Q12. Which players have won the Orange Cap more than once, and how many times?
SELECT PLAYERS.PLAYER_NAME , COUNT(*) AS ORANGE_CAP
FROM ORANGE_CAP_WINNERS
JOIN PLAYERS ON ORANGE_CAP_WINNERS.PLAYER_ID=PLAYERS.PLAYER_ID
GROUP BY PLAYERS.PLAYER_NAME
HAVING ORANGE_CAP > 1
ORDER BY ORANGE_CAP DESC;

-- Q13. Which players have won the Purple Cap more than once, and how many times?
SELECT PLAYERS.PLAYER_NAME , COUNT(*) AS PURPLE_CAP
FROM PURPLE_CAP_WINNERS
JOIN PLAYERS ON PURPLE_CAP_WINNERS.PLAYER_ID=PLAYERS.PLAYER_ID
GROUP BY PLAYERS.PLAYER_NAME
HAVING PURPLE_CAP > 1
ORDER BY PURPLE_CAP DESC;

-- Q14. Show the top 5 highest run-scoring Orange Cap seasons with the player, team and year.
SELECT SEASONS.SEASON_YEAR , PLAYERS.PLAYER_NAME , TEAMS.TEAM_NAME , O.RUNS_SCORED
FROM ORANGE_CAP_WINNERS O
JOIN SEASONS ON O.SEASON_ID=SEASONS.SEASON_ID
JOIN PLAYERS ON O.PLAYER_ID=PLAYERS.PLAYER_ID
JOIN TEAMS ON O.TEAM_ID=TEAMS.TEAM_ID
ORDER BY O.RUNS_SCORED DESC
LIMIT 5;

-- Q15. Which teams have won the most individual awards (Orange Cap and Purple Cap combined)? Show the split too.
SELECT TEAMS.TEAM_NAME , SUM(A.ORANGE) AS ORANGE_CAP , SUM(A.PURPLE) AS PURPLE_CAP , SUM(A.ORANGE)+SUM(A.PURPLE) AS TOTAL_CAPS
FROM 
(
SELECT TEAM_ID , 1 AS ORANGE , 0 AS PURPLE FROM ORANGE_CAP_WINNERS
UNION ALL
SELECT TEAM_ID , 0 AS ORANGE , 1 AS PURPLE FROM PURPLE_CAP_WINNERS
)A
JOIN TEAMS ON A.TEAM_ID=TEAMS.TEAM_ID
GROUP BY TEAMS.TEAM_NAME
ORDER BY TOTAL_CAPS DESC;

-- Q16. In which seasons did the champion team also own the Orange Cap winner?
SELECT SEASONS.SEASON_YEAR , TEAMS.TEAM_NAME , PLAYERS.PLAYER_NAME , O.RUNS_SCORED
FROM SEASONS
JOIN ORANGE_CAP_WINNERS O ON SEASONS.SEASON_ID=O.SEASON_ID
JOIN TEAMS ON SEASONS.CHAMPION_TEAM_ID=TEAMS.TEAM_ID
JOIN PLAYERS ON O.PLAYER_ID=PLAYERS.PLAYER_ID
WHERE SEASONS.CHAMPION_TEAM_ID = O.TEAM_ID;


-- Q17. Rank all teams by titles won using DENSE_RANK, including teams with zero titles.
SELECT TEAM_NAME , TITLES_WON , DENSE_RANK() OVER (ORDER BY TITLES_WON DESC) AS TITLE_RANK
FROM (SELECT TEAMS.TEAM_NAME , COUNT(SEASONS.SEASON_ID) AS TITLES_WON
FROM TEAMS
LEFT JOIN SEASONS ON TEAMS.TEAM_ID = SEASONS.CHAMPION_TEAM_ID
      GROUP BY TEAMS.TEAM_NAME) X
ORDER BY TITLE_RANK;

-- Q18. Which venues have hosted the most finals? Use RANK so ties are shown together.
SELECT VENUE_NAME , FINALS_HOSTED , RANK() OVER (ORDER BY FINALS_HOSTED DESC) AS VENUE_RANK
FROM (SELECT VENUES.VENUE_NAME , COUNT(*) AS FINALS_HOSTED
FROM SEASONS
JOIN VENUES ON SEASONS.FINAL_VENUE_ID=VENUES.VENUE_ID
GROUP BY VENUES.VENUE_NAME)A;

-- Q19. For each active team, what percentage of its squad is overseas? Show only teams where overseas players are more than 30% of the squad.
SELECT TEAMS.TEAM_NAME , COUNT(*) AS SQUAD_SIZE,
SUM(CASE WHEN PLAYERS.NATIONALITY<>"INDIA" THEN 1 ELSE 0 END) AS OVERSEAS,
ROUND(100.0*SUM(CASE WHEN PLAYERS.NATIONALITY<>"INDIA" THEN 1 ELSE 0 END)/COUNT(*),2) AS OVERSEAS_PERCENTAGE
FROM TEAMS
JOIN PLAYERS
ON TEAMS.TEAM_ID=PLAYERS.CURRENT_TEAM_ID
GROUP BY TEAMS.TEAM_NAME
HAVING 100.0*SUM(CASE WHEN PLAYERS.NATIONALITY<>"INDIA" THEN 1 ELSE 0 END)/COUNT(*) > 30
ORDER BY OVERSEAS_PERCENTAGE DESC;	

-- Q20. How did the Orange Cap run total change compared to the previous season? Use LAG.
SELECT SEASONS.SEASON_YEAR , PLAYERS.PLAYER_NAME , O.RUNS_SCORED,
LAG(O.RUNS_SCORED) OVER (ORDER BY SEASONS.SEASON_YEAR) AS PREVIOUS_SEASON_RUNS,
O.RUNS_SCORED-LAG(O.RUNS_SCORED) OVER (ORDER BY SEASONS.SEASON_YEAR) AS RUNS_DIFFERENCE
FROM ORANGE_CAP_WINNERS O
JOIN SEASONS ON O.SEASON_ID=SEASONS.SEASON_ID
JOIN PLAYERS ON O.PLAYER_ID=PLAYERS.PLAYER_ID
ORDER BY SEASONS.SEASON_YEAR;
