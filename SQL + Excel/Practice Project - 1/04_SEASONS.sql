CREATE TABLE SEASONS (
    SEASON_ID INT PRIMARY KEY,
    SEASON_YEAR INT NOT NULL,
    TEAMS_PARTICIPATED INT NOT NULL,
    TOTAL_MATCHES INT NOT NULL,
    CHAMPION_TEAM_ID INT NOT NULL,
    RUNNER_UP_TEAM_ID INT NOT NULL,
    FINAL_VENUE_ID INT NOT NULL,
    FOREIGN KEY (CHAMPION_TEAM_ID) REFERENCES TEAMS (TEAM_ID),
    FOREIGN KEY (RUNNER_UP_TEAM_ID) REFERENCES TEAMS (TEAM_ID),
    FOREIGN KEY (FINAL_VENUE_ID) REFERENCES VENUES (VENUE_ID)
);

